"""Generate browser property tables from Unicode 18, without host ICU data."""
import json
from audit import DATA, ROOT, VERSION, code_range, records, properties


def table(path, select):
    rows = []
    for fields in records(DATA / path):
        value = select(fields)
        if value is not None:
            points = code_range(fields[0])
            rows.append([points.start, points.stop - 1, value])
    rows.sort()
    merged = []
    for first, last, value in rows:
        if merged and merged[-1][1] + 1 == first and merged[-1][2] == value:
            merged[-1][1] = last
        else:
            merged.append([first, last, value])
    return merged


def categories():
    rows = []
    start = None
    for f in records(DATA / 'UnicodeData.txt'):
        cp = int(f[0], 16)
        if f[1].endswith(', First>'):
            start = cp
            continue
        first = start if f[1].endswith(', Last>') else cp
        start = None
        if rows and rows[-1][1] + 1 == first and rows[-1][2] == f[2]:
            rows[-1][1] = cp
        else:
            rows.append([first, cp, f[2]])
    return rows


def bidi_classes():
    path = DATA / 'extracted/DerivedBidiClass.txt'
    values = ['L'] * 0x110000
    aliases = {'Left_To_Right': 'L', 'Right_To_Left': 'R', 'Arabic_Letter': 'AL', 'European_Terminator': 'ET'}
    for line in path.read_text().splitlines():
        if line.startswith('# @missing:'):
            points, name = line.split(':', 1)[1].strip().split(';')
            for cp in code_range(points.strip()):
                values[cp] = aliases[name.strip()]
    for points, value in records(path):
        for cp in code_range(points):
            values[cp] = value
    result = []
    for cp, value in enumerate(values):
        if result and result[-1][2] == value:
            result[-1][1] = cp
        else:
            result.append([cp, cp, value])
    return result


def build():
    scripts = properties(DATA / 'Scripts.txt')
    joining = {scripts.get(int(f[0], 16)) for f in records(DATA / 'ArabicShaping.txt')
               if f[2] in {'D', 'R', 'L'} and scripts.get(int(f[0], 16)) not in {'Common', 'Inherited'}}
    tables = {
        "fontDependentFormat": table("PropList.txt", lambda f: True if f[1] == "Prepended_Concatenation_Mark" else None),
        "joiningFontCharacters": table("ArabicShaping.txt", lambda f: True if scripts.get(int(f[0],16)) in joining else None),
        "joiningScript": table("Scripts.txt", lambda f: f[1] if f[1] in joining else None),
        # UVS font selection must retain the rest of a contextual script, even
        # when its letters do not have ArabicShaping joining types (Myanmar).
        "variationContextScript": table("Scripts.txt", lambda f: f[1] if f[1] not in {
            "Common", "Inherited", "Unknown", "Latin", "Greek", "Cyrillic",
            "Han", "Hiragana", "Katakana", "Hangul", "Bopomofo", "Yi",
            "Tangut", "Nushu", "Khitan_Small_Script", "Seal", "Jurchen",
            "Egyptian_Hieroglyphs"} else None),
        "gridSimple": table("Scripts.txt", lambda f: True if f[1] in {
            "Common", "Inherited", "Latin", "Greek", "Cyrillic", "Han", "Hiragana",
            "Katakana", "Hangul", "Bopomofo", "Yi", "Tangut", "Nushu",
            "Khitan_Small_Script", "Seal", "Jurchen"} else None),
        "gridWide": table("EastAsianWidth.txt", lambda f: True if f[1] in {"F", "W"} else None),
        "emojiVariationBases": sorted({int(f[0].split()[0],16) for f in records(DATA / 'emoji/emoji-variation-sequences.txt')}),
        "emojiPresentation": table("emoji/emoji-data.txt", lambda f: True if f[1] == "Emoji_Presentation" else None),
        "bidiClass": bidi_classes(),
        "bidiBrackets": [[int(f[0], 16), int(f[1], 16), f[2]] for f in records(DATA / 'BidiBrackets.txt')],
        "lineBreak": table("LineBreak.txt", lambda f: f[1]),
        "eastAsianWidth": table("EastAsianWidth.txt", lambda f: True if f[1] in {"F", "W", "H"} else None),
        "generalCategory": categories(),
        "graphemeBreak": table("auxiliary/GraphemeBreakProperty.txt", lambda f: f[1]),
        "indicConjunctBreak": table("DerivedCoreProperties.txt", lambda f: f[2] if f[1] == "InCB" else None),
        "extendedPictographic": table("emoji/emoji-data.txt", lambda f: True if f[1] == "Extended_Pictographic" else None),
    }
    header = (f"// Generated by tools/unicode/build_tables.py from Unicode {VERSION}.\n"
              "// Unicode data licence: ../data/unicode/LICENSE.txt. Do not edit.\n")
    return header + "\n".join(f"export const {name} = {json.dumps(value, separators=(',', ':'))};"
                              for name, value in tables.items()) + "\n"


if __name__ == "__main__":
    (ROOT / "js/unicode-data.js").write_text(build())
